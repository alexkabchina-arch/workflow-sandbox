"""Проверка круглой суммы: целое число рублей, без копеек; возврат зеркален продаже."""

# Условие #143: бонус за круглую сумму (PRD #142); на проверку круглости не влияет
ROUND_BONUS_KOP = 100


def is_round_rub(total_kop: int) -> bool:
    # Делитель — копеек в рубле, не бонус. Знак отдельно не нужен: остаток % в Python неотрицателен
    return total_kop % 100 == 0
